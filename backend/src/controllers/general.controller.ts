// ═══════════════════════════════════════════════════════════════════════════════

export const getSeoByPath = async (req: Request, res: Response): Promise<void> => {
  try {
    let pathParam = req.params.path || '';
    let pagePath = decodeURIComponent(pathParam);
    if (!pagePath.startsWith('/')) {
      pagePath = '/' + pagePath;
    }
    const setting = await prisma.sEOSetting.findUnique({ where: { pagePath } });
    if (!setting) {
      res.status(404).json({ success: false, message: 'SEO setting not found.' });
      return;
    }
    res.status(200).json({ success: true, data: setting });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to fetch SEO setting.' });
  }
};

export const upsertSeoSetting = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { pagePath, metaTitle, metaDescription, keywords, ogTitle, ogDescription, ogImage, schemaMarkup } = req.body;
    if (!pagePath || !metaTitle || !metaDescription) {
      res.status(400).json({ success: false, message: 'pagePath, metaTitle, and metaDescription are required.' });
      return;
    }
    const setting = await prisma.sEOSetting.upsert({
      where: { pagePath },
      update: { metaTitle, metaDescription, keywords: keywords || [], ogTitle, ogDescription, ogImage, schemaMarkup },
      create: { pagePath, metaTitle, metaDescription, keywords: keywords || [], ogTitle, ogDescription, ogImage, schemaMarkup },
    });
    res.status(200).json({ success: true, data: setting });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to save SEO setting.' });
  }
};

