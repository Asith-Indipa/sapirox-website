export const submitContactMessage = async (req: Request, res: Response): Promise<void> => {
  try {
    const { name, email, subject, message } = req.body;
    if (!name || !email || !message) {
      res.status(400).json({ success: false, message: 'Name, email, and message are required.' });
      return;
    }
    const contactMessage = await prisma.contactMessage.create({
      data: { name, email, subject: subject || null, message },
    });

    // Send email alert via Resend SDK
    if (resend) {
      try {
        await resend.emails.send({
          from: 'Sapirox Web <onboarding@resend.dev>', // Resend standard sandbox sender
          to: 'info@sapirox.com',
          subject: `[Lead Notification] ${subject || 'New Contact Request'}`,
          html: `
            <div style="font-family: Arial, sans-serif; line-height: 1.6; color: #333; max-width: 600px; margin: auto; padding: 20px; border: 1px solid #ddd; border-radius: 8px;">
              <h2 style="color: #4f46e5; border-bottom: 2px solid #f3f4f6; padding-bottom: 10px;">New Contact Lead Received</h2>
              <p><strong>Name:</strong> ${name}</p>
              <p><strong>Email:</strong> <a href="mailto:${email}">${email}</a></p>
              <p><strong>Subject:</strong> ${subject || 'N/A'}</p>
              <div style="background-color: #f9fafb; padding: 15px; border-left: 4px solid #4f46e5; border-radius: 4px; margin-top: 20px;">
                <p style="margin: 0; font-style: italic;">"${message}"</p>
              </div>
              <footer style="margin-top: 30px; font-size: 11px; color: #666; text-align: center; border-top: 1px solid #f3f4f6; padding-top: 15px;">
                This message was automatically generated by Sapirox CMS Portal.
              </footer>
            </div>
          `
        });
        console.log('✅ Email notification sent successfully via Resend');
      } catch (emailErr) {
        console.error('⚠️ Failed to send email via Resend:', emailErr);
      }
    }

    res.status(201).json({ success: true, data: contactMessage });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to send message.' });
  }
};

export const getAllMessages = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { status } = req.query;
    const where: Record<string, unknown> = {};
    if (status) where.status = status as string;

    const messages = await prisma.contactMessage.findMany({
      where,
      orderBy: { createdAt: 'desc' },
    });
    res.status(200).json({ success: true, data: messages });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to fetch messages.' });
  }
};

export const updateMessageStatus = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const { status } = req.body;
    if (!status || !['UNREAD', 'REPLIED', 'ARCHIVED', 'DELETED'].includes(status)) {
      res.status(400).json({ success: false, message: 'Valid status required.' });
      return;
    }
    const message = await prisma.contactMessage.update({
      where: { id },
      data: { status },
    });
    res.status(200).json({ success: true, data: message });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to update message.' });
  }
};

